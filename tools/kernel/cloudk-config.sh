cloudk_config() {
  local s
  for s in $CLOUDK_OPT_Y $CLOUDK_REQ_Y; do scripts/config -e "$s"; done
  for s in $CLOUDK_OPT_M; do scripts/config -m "$s"; done
  for s in $CLOUDK_OPT_N $CLOUDK_REQ_N; do scripts/config -d "$s"; done
  scripts/config --set-str LOCALVERSION "-cloudk-$CLOUDK_VER"
  scripts/config --set-str DEFAULT_HOSTNAME cloudos
  scripts/config --set-str MODULE_SIG_HASH sha512
  scripts/config --set-str DEFAULT_TCP_CONG bbr
  scripts/config --set-str LSM "landlock,lockdown,yama,apparmor,bpf"
  if [ -f "$CLOUDK_REGDIR/regulatory.db" ] && [ -f "$CLOUDK_REGDIR/regulatory.db.p7s" ]; then
    scripts/config --set-str EXTRA_FIRMWARE "regulatory.db regulatory.db.p7s" --set-str EXTRA_FIRMWARE_DIR "$CLOUDK_REGDIR"
  elif [ "${CLOUDK_NO_REGDB:-0}" != 1 ]; then
    die "нет $CLOUDK_REGDIR/regulatory.db, поставь wireless-regdb (CLOUDK_NO_REGDB=1 отключает проверку)"
  fi
}

cloudk_verify() {
  local s bad="" opt=""
  for s in $CLOUDK_REQ_Y; do grep -q "^CONFIG_$s=y$" .config || bad="$bad $s"; done
  for s in $CLOUDK_REQ_N; do ! grep -q "^CONFIG_$s=[ym]$" .config || bad="$bad !$s"; done
  [ -z "$bad" ] || die "обязательные опции ядра не встали:$bad"
  for s in $CLOUDK_OPT_Y; do grep -q "^CONFIG_$s=y$" .config || opt="$opt $s"; done
  for s in $CLOUDK_OPT_M; do grep -q "^CONFIG_$s=m$" .config || opt="$opt $s"; done
  for s in $CLOUDK_OPT_N; do ! grep -q "^CONFIG_$s=[ym]$" .config || opt="$opt !$s"; done
  : > "$CLOUDK_MISSING"
  if [ -n "$opt" ]; then printf '%s\n' $opt > "$CLOUDK_MISSING"; echo "!! необязательные опции не встали (список в $CLOUDK_MISSING):$opt" >&2; fi
}
